"""Generate the HIP sources of the DeepSeek family's native kernels (the text path) from TensorFold's CUDA sources
(bertholomus/TensorFold strix-port-base: zig/kernels/cuda/dsv41_ops.cu, dsv41_torch.cu, torch_ops/pointwise.cu and
movement.cu; Apache-2.0), and build gfx1151 code objects with hipcc --genco.

Kernel bodies are copied verbatim (extern "C" __global__ functions and the device helpers / structs they use; the
CUDA host launchers and the vision kernels are left out); the CUDA spellings map onto HIP in tf_hip_compat.h, and the
three PTX constructs are replaced by name (EDITS, each applied exactly the stated number of times):
  - %globaltimer (tf_ds_clock_kernel, profiling only): wall_clock64() scaled to ns (the constant 100 MHz clock of
    gfx11; the test reads hipDeviceAttributeWallClockRate and checks it);
  - tf_ds_l2_prefetch_kernel's cp.async.bulk.prefetch.L2 / prefetch.global.L2: the kernel returns at once (it moves no
    data any kernel reads; the paced L2 warm-up is a CUDA-side tuning, to be revisited for AMD).
Build: hipcc --genco --offload-arch=gfx1151 -O3 -ffp-contract=off (the CUDA build's --fmad=false; fp32 denormals are
kept, as --ftz=false).

Usage: python make_hip.py UPSTREAM_DIR OUT_DIR
"""

import hashlib
import re
import subprocess
import sys
from pathlib import Path

TEXT_KERNELS = {
    "dsv41_ops": ["tf_ds_f16_to_f32_kernel", "tf_ds_add2_bf16_kernel", "tf_ds_clock_kernel", "tf_ds_topk_i64_kernel",
                  "tf_ds_scatter_rows_kernel", "tf_ds_topk_indices_kernel", "tf_ds_l2_prefetch_kernel",
                  "tf_ds_iota_vis_kernel", "tf_ds_cand_fast_kernel", "tf_ds_block_max_kernel", "tf_ds_pool_pick_kernel",
                  "tf_ds_apply_pool_kernel", "tf_ds_copy_rows16_kernel", "tf_ds_argmax_rows_kernel"],
    "dsv41_torch": ["tf_ds_rms_norm_kernel", "tf_ds_compress2_kernel", "tf_ds_rope_kernel", "tf_ds_bf16_scale_kernel",
                    "tf_ds_hc_mean4_kernel"],
    "pointwise": ["tf_bf16_to_f32_kernel", "tf_f32_to_bf16_kernel"],
    "movement": ["tf_gather_rows_kernel", "tf_strided_copy_kernel"],
}
HELPERS = {
    "dsv41_ops": ["tf_ds_score_key", "struct TfDsPrefetch"],
}
EDITS = [
    ("tf_ds_clock_kernel", 'asm volatile("mov.u64 %0, %%globaltimer;" : "=l"(t));', "t = wall_clock64() * 10ull;  // HIP: 100 MHz", 1),
]
COMPAT = r'''// HIP spellings of the CUDA names TensorFold's kernels use (generated by make_hip.py)
#pragma once
#include <hip/hip_runtime.h>
#include <hip/hip_bf16.h>
#include <hip/hip_fp16.h>
#include <stdint.h>
typedef __hip_bfloat16 __nv_bfloat16;
// HIP's float -> bf16 conversion is the __bf16 fptrunc: round to nearest even (t_native checks it exhaustively)
#define __float2bfloat16_rn(x) __float2bfloat16(x)
// gfx1151 runs wave32: a CUDA warp's full-mask shuffles are the wave's
#define __shfl_down_sync(mask, v, off) __shfl_down((v), (off), 32)
'''


def extract(text, name):
    """The source of `extern "C" __global__ ... name(...) {...}` or of a helper / struct, by brace matching."""
    if name.startswith("struct "):
        m = re.search(r"\n" + re.escape(name) + r"\s*\{", text)
    else:
        m = re.search(r"\n(extern \"C\" __global__[^\n]*\b|__device__[^\n]*\b)" + re.escape(name) + r"\(", text)
    if not m:
        raise SystemExit(f"{name}: not found")
    start = m.start() + 1
    # include the comment block right above
    pre = text[:start].rstrip("\n").split("\n")
    k = len(pre)
    while k > 0 and pre[k - 1].startswith("//"):
        k -= 1
    cstart = len("\n".join(pre[:k])) + (1 if k else 0)
    i = text.index("{", start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                end = j + 1
                if name.startswith("struct "):
                    end = text.index(";", end) + 1
                return text[cstart:end]
    raise SystemExit(f"{name}: unbalanced")


def l2_prefetch_noop(src):
    """tf_ds_l2_prefetch_kernel with its body replaced by a return (the signature kept)."""
    i = src.index("{", src.index("tf_ds_l2_prefetch_kernel("))
    return src[:i] + "{\n    // HIP: a no-op (the CUDA build's paced L2 prefetch moves no data a kernel reads)\n    (void)a; (void)delay_ns; (void)wave_ns;\n}"


def main(updir, outdir):
    up, out = Path(updir), Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "tf_hip_compat.h").write_text(COMPAT)
    used = [0] * len(EDITS)
    files = {"dsv41_ops": "dsv41_ops.cu", "dsv41_torch": "dsv41_torch.cu", "pointwise": "pointwise.cu",
             "movement": "movement.cu"}
    for mod, fname in files.items():
        text = (up / fname).read_text()
        h = hashlib.sha256(text.encode()).hexdigest()
        parts = [f"// HIP port of TensorFold {fname} (sha256 {h}), Apache-2.0; generated by make_hip.py.\n"
                 f"// Text-path kernels only; bodies verbatim except the edits listed in make_hip.py.\n"
                 f'#include "tf_hip_compat.h"\n']
        if mod == "dsv41_torch":
            parts.append("#define TF_FULL_MASK 0xffffffffu\n")
        for hname in HELPERS.get(mod, []):
            parts.append(extract(text, hname))
        for kname in TEXT_KERNELS[mod]:
            src = extract(text, kname)
            for e, (m, old, new, n) in enumerate(EDITS):
                if m == kname and old in src:
                    used[e] += src.count(old)
                    src = src.replace(old, new)
            if kname == "tf_ds_l2_prefetch_kernel":
                src = l2_prefetch_noop(src)
            if "asm" in src:
                raise SystemExit(f"{kname}: inline asm left")
            parts.append(src)
        (out / f"{mod}.hip").write_text("\n\n".join(parts) + "\n")
    for e, (m, old, new, n) in enumerate(EDITS):
        if used[e] != n:
            raise SystemExit(f"edit {e} applied {used[e]} times, expected {n}")
    for mod in files:
        cmd = ["/usr/bin/hipcc", "--genco", "--offload-arch=gfx1151", "-O3", "-ffp-contract=off",
               "-o", str(out / f"{mod}.hsaco"), str(out / f"{mod}.hip")]
        r = subprocess.run(cmd, capture_output=True, text=True)
        print(" ".join(cmd), "->", r.returncode)
        if r.returncode:
            print(r.stderr[-4000:])
            raise SystemExit(1)
        print(f"  {mod}.hsaco sha256 {hashlib.sha256((out / f'{mod}.hsaco').read_bytes()).hexdigest()}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
